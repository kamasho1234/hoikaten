const FORM_LABEL = {
  standard: "標準様式",
  "standard-plus": "標準様式＋自治体の欄",
  original: "独自様式",
} as const;

/** 自治体別記事の一覧（都道府県順）。レコードが増えれば自動で増える */
function cityList(): string {
  const rows = shurouRecords
    .map((r) => ({ r, info: getCityInfo(r.citySlug) }))
    .filter((x) => x.info)
    .sort((a, b) => {
      const pa = PREF_ORDER.indexOf(a.info!.prefecture);
      const pb = PREF_ORDER.indexOf(b.info!.prefecture);
      return pa !== pb ? pa - pb : a.info!.name.localeCompare(b.info!.name, "ja");
    });
  const counts = { standard: 0, "standard-plus": 0, original: 0 };
  for (const { r } of rows) counts[r.formType] += 1;
  const trs = rows
    .map(
      ({ r, info }) =>
        `<tr><td>${info!.prefecture}</td><td><a href="/${r.citySlug}/articles/${r.slug ?? "shurou-shoumeisho"}">${info!.name}</a></td><td>${FORM_LABEL[r.formType]}</td><td>${r.validity ?? "記載なし"}</td><td>${r.seal === "required" ? "必要" : r.seal === "not-required" ? "不要" : "記載なし"}</td></tr>`,
    )
    .join("\n");
  return `
<p>このサイトが公式ページを1つずつ確かめた${rows.length}自治体の一覧です（標準様式 ${counts.standard}、標準様式に自治体の欄を足したもの ${counts["standard-plus"]}、独自様式 ${counts.original}）。自治体名を押すと、様式の入手先・締切・提出先・自営業の添付書類まで載せた記事に移ります。</p>
<table>
<thead><tr><th>都道府県</th><th>自治体</th><th>様式</th><th>証明日の有効期限</th><th>押印</th></tr></thead>
<tbody>
${trs}
</tbody>
</table>`;
}

