function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** 自治体別記事の一覧（都道府県順）。レコードが増えれば自動で増える */
function cityList(): string {
  const rows = ichijiRecords
    .map((r) => ({ r, info: getCityInfo(r.citySlug) }))
    .filter((x) => x.info)
    .sort((a, b) => {
      const pa = PREF_ORDER.indexOf(a.info!.prefecture);
      const pb = PREF_ORDER.indexOf(b.info!.prefecture);
      return pa !== pb ? pa - pb : a.info!.name.localeCompare(b.info!.name, "ja");
    });
  if (rows.length === 0) return "";
  // 表は一覧性が要るので、長い値は最初の一区切りだけ出す（全文は自治体の記事にある）
  const brief = (v?: string) => {
    if (!v) return "記載なし";
    let head = v.split("。")[0];
    if (head.length > 60) head = head.slice(0, 60);
    return esc(head.length < v.length ? `${head}…` : v);
  };
  const trs = rows
    .map(
      ({ r, info }) =>
        `<tr><td>${info!.prefecture}</td><td><a href="/${r.citySlug}/articles/ichiji-hoiku">${info!.name}</a></td><td>${brief(r.azukariLimit)}</td><td>${brief(r.azukariFees?.[0])}</td><td>${brief(r.daredemoHours)}</td></tr>`,
    )
    .join("\n");
  return `
<h2>公式ページで確かめた自治体の一覧</h2>
<p>このサイトが公式ページを1つずつ確かめた${rows.length}自治体です。自治体名を押すと、理由の区分・上限・料金表・登録と予約・実施施設・こども誰でも通園制度の時間まで載せた記事に移ります。表の料金は代表的な区分1つだけで、区分ごとの額は記事にあります。</p>
<table>
<thead><tr><th>都道府県</th><th>自治体</th><th>一時預かりの上限</th><th>料金（代表例）</th><th>誰でも通園の月時間</th></tr></thead>
<tbody>
${trs}
</tbody>
</table>`;
}

